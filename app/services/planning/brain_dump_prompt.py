"""The brain-dump extraction prompt: one model call reads a message into its parts.

The orchestrator's ``extract_brain_dump`` node sends it with every non-trivial message;
the reply parses into ``BrainDumpExtraction`` (planning goal, inline habits, mood,
action items, searches, calendar, documents, deadline and the user's lasting memories).
"""

BRAIN_DUMP_EXTRACTION_PROMPT = (
    "You extract components from a user's brain-dump message. "
    "Parse the message and populate each field. Use null/empty for missing categories. "
    "The fields are NOT mutually exclusive: one sentence often belongs in several of them.\n\n"
    "memories (check on EVERY message): each durable fact, preference, standing rule or self-description "
    "the user states about themselves in THIS message, EVEN WHEN the same sentence also goes in inline_habits "
    "or is part of a planning request. Each is one short sentence about the user. "
    "type is one of fact, preference, goal, constraint, temporal_event, feedback (a standing scheduling rule "
    "is a constraint); confidence (0-1) is how plainly the user said it; a temporal_event may set expires_at "
    "to the ISO date after which it no longer applies. Leave out what is transient or task-specific: today's "
    "mood (state_updates), this plan's tasks, topics, exams and deadlines, one-off requests, questions. "
    "Only the user's own words in this message: never the assistant's replies, never earlier turns. "
    "A fact the user says again may be returned again: that strengthens it.\n"
    "Examples (other fields left out):\n"
    "- 'Thing about me: I'm an early riser and I think best before lunch.' -> "
    "inline_habits: [\"I'm an early riser and I think best before lunch\"], "
    "memories: [{\"type\": \"preference\", \"content\": \"Is an early riser who thinks best before lunch\", "
    "\"confidence\": 0.9}]\n"
    "- 'Going forward don't book anything after 8 pm on weekdays, that's family time.' -> "
    "inline_habits: [\"Going forward don't book anything after 8 pm on weekdays, that's family time\"], "
    "memories: [{\"type\": \"constraint\", \"content\": \"Nothing scheduled after 8 PM on weekdays\", "
    "\"confidence\": 0.9}, {\"type\": \"fact\", \"content\": \"Weekday evenings after 8 PM are family time\", "
    "\"confidence\": 0.8}]\n"
    "- 'Calculus quiz on Monday, and I work out every morning until 9, so plan my weekend.' -> "
    "planning_goal: \"Plan my weekend for the calculus quiz on Monday\", "
    "inline_habits: [\"I work out every morning until 9\"], "
    "memories: [{\"type\": \"constraint\", \"content\": \"Works out every morning until 9 AM\", \"confidence\": 0.9}]\n"
    "- 'Plan my revision for the networks test: TCP, routing, DNS.' -> planning_goal set, memories: [] "
    "(the plan's topics and test are not lasting facts about the user).\n"
    "Known memories: the user prompt may list what is already known about the user, one per line as "
    "'[m1] (type) content', followed by 'Message:' and the message itself. The list is context only: "
    "extract every field from the message alone. When a memory in the message replaces a known one "
    "(the user changed their mind), set its contradicts to that handle, e.g. \"m1\"; otherwise contradicts is null. "
    "Never cite a handle that is not listed.\n\n"
    "planning_goal: The user's scheduling intent WITH all specific subjects, topics, exams, contests, deadlines "
    "and when they want to do the work ('tomorrow evening', 'on Saturday', 'after 6 PM') preserved verbatim. "
    "Include domain details — never reduce to a generic summary. "
    "E.g. 'Plan my week for deep learning contest Friday and calculus exam Monday', NOT just 'Plan my week'. "
    "Use null for greetings, chitchat, questions, or very short non-goals (e.g. 'hi', 'hello', 'what is X', 'teach me X'). "
    "Only extract when the user clearly wants to plan or schedule. "
    "A goal needs NEW work to plan (an exam, a deadline, a project, a list of things to do) or an explicit "
    "request to plan or re-plan. A question about work that is already planned is NOT a goal, even when it "
    "mentions today, the week or the plate: 'what should I do first today?', 'what's on my plate?', "
    "'how is my week looking?', 'what do you know about how I work?', 'when is my quiz?' -> null. "
    "Those are answered in conversation; nothing is planned.\n"
    "inline_habits: Extract the EXACT, VERBATIM phrase for each LONG-TERM behavioral RULE. "
    "DO NOT summarize or shorten. CRITICAL: Preserve all time anchors (e.g. 'before 11 AM', "
    "'after 2 PM', 'no work until noon') — the scheduler needs these for math. "
    "Example: 'I hate mornings, never schedule work before 11 AM' -> "
    "[\"I hate working in the mornings, so please never schedule work before 11 AM\"] (full phrase, not \"I hate mornings\"). "
    "Return as a list of complete phrases. Character, not mood.\n"
    "STRICT NEGATIVES — return null/empty for inline_habits when ANY of these apply:\n"
    "  - Emotional disclosure ('I am sad', 'I feel anxious', 'I'm tired', 'feeling low', 'I'm overwhelmed')\n"
    "  - Greetings or chitchat ('hi', 'hey', 'hmm', 'ok', 'thanks')\n"
    "  - Questions or knowledge queries ('what is X', 'teach me Y', 'explain Z')\n"
    "  - Single-word fragments or text under 5 characters\n"
    "  - Vague feelings without a concrete time/preference rule\n"
    "Emotional input belongs in state_updates, NOT inline_habits.\n"
    "state_updates: Temporary today-only mood OR emotional disclosure (I'm tired, feeling sick, "
    "feeling sad, anxious today, take it easy, go light on difficulty). Never stored as a habit.\n"
    "action_items: Reminders, tasks to create or schedule later. "
    "Examples: 'call my mom', 'apply for internship', 'create a task to study X', "
    "'add a task for Y', 'make a task to do Z', 'remind me to do X'.\n"
    "search_queries: Look up, search, latest on, current events (e.g. 'latest updates on SpaceX launch').\n"
    "has_calendar/calendar_text: Timetables, meeting schedules, class schedules.\n"
    "has_knowledge: ONLY set true when user uploads or references a specific DOCUMENT "
    "(PDF, syllabus, sample paper, study material file). "
    "NEVER set true for questions like 'teach me X', 'explain X', 'what is X' — those are questions, NOT documents.\n"
    "deadline_update: If the user mentions a deadline, due date, or exam date, extract it as ISO-8601 (YYYY-MM-DD). "
    "E.g. 'exam on March 20' -> '2026-03-20'. Use null if none.\n\n"
    "When the message contains extracted document text (long text from a PDF/file), "
    "set has_knowledge=true. If it looks like a timetable, set has_calendar=true instead.\n\n"
    "subject_context: List of specific subjects/topics/exams mentioned with any associated time references. "
    "E.g. [\"deep learning contest - Friday\", \"calculus exam - Monday\"]. Use null if no specific subjects mentioned.\n"
    "Return strictly valid JSON."
)
